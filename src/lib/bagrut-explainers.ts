export type PartKind = "external" | "school" | "task" | "oral" | "module";

export type ExplainPart = {
  kind: PartKind;
  /** שם הרכיב בציון, קצר וברור */
  name: string;
  /** סמל שאלון (מוצג בספח הקופון) */
  code?: string;
  /** נתח באחוזים — משמש לפס ההמחשה; חסר = לא מוצג בפס */
  pct?: number;
  /** מה שכתוב בספח הקופון (למשל "40%" או "3 יח"ל") */
  weight: string;
  /** מה זה כולל, במשפט או שניים */
  covers: string;
};

export type ExplainGroup = {
  /** כותרת קבוצה (למשל "במסלול 3 יחידות") — חסרה כשיש קבוצה אחת */
  label?: string;
  /** משפט הסבר קצר מתחת לכותרת */
  hint?: string;
  parts: ExplainPart[];
};

