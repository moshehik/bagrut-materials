/**
 * ניסוח התשובות של הסוכן אל המורה (reply_text / note) – לוגיקה טהורה (בלי DB), נבדקת ב-scripts/reply-text.test.ts.
 *
 * הכלל (המורה, 2026-11-08): בתשובה למורה **לעולם לא מציינים את שם האתר/הספרייה שממנה נלקח המקור** – לא "ספריא", לא "ספריה",
 * לא "Sefaria". הסוכן כן יכול (ואמור) להביא את דברי המפרשים ממקור מאומת – אבל המורה רואה רק מה שנוסף, לא מאיפה הועתק.
 * שלוש שכבות: (1) validateReplyText – נדחה בצד השרת (סכמת ה-API של הסוכן וגם הפקודות הישירות) עם הודעה ברורה,
 * כדי שהסוכן ינסח מחדש; (2) sanitizeReplyForDisplay – רשת ביטחון בתצוגה, שמסירה משפט-משנה שמזכיר את המקור (שמרנית:
 * מסירה רק תבניות מוכרות, ולא נוגעת בטקסט שלא תואם); (3) ההנחיות לסוכן (fix-reports.md) ולג'מיני (fix-writing-guidelines.ts).
 */

/** האותיות העבריות – לשימוש בגבולות מילה (\b לא עובד בעברית) */
const HE = "א-ת";
/** תחיליות עבריות נפוצות (ב/ל/מ/ה/ו/כ/ש) לפני שם המקור: "בספריא", "מהספריה", "וספריא" */
const PREFIX = "[ובלכמהש]{0,3}";
/** שמות המקור האסורים: ספריא / ספריה / ספרייה / ספאריה / ספריית (בנייה סמוכה) / Sefaria. לא תופס "ספריהם", "ספרי" (מדרש ספרי) */
const NAME = "(?:ספריא|ספריה|ספרייה|ספאריה|ספריית|sefaria)";
/** שם המקור כמילה שלמה (עם תחילית) */
const NAME_WORD = `(?<![${HE}])${PREFIX}${NAME}(?![${HE}])`;

const FORBIDDEN_RE = new RegExp(NAME_WORD, "i");

/** האם הטקסט מזכיר את אתר/ספריית המקור (ספריא וכד') */
export function mentionsSourceLibrary(text: string): boolean {
  return FORBIDDEN_RE.test(text);
}

export const REPLY_LIBRARY_ERROR =
  'התשובה מזכירה את שם האתר/הספרייה שממנה נלקח המקור ("ספריא" / "ספריה" / Sefaria). בתשובה למורה לא מציינים מאיפה הועתק המקור – רק מה נוסף או תוקן ובאיזה מפרש. נסחו מחדש בלי אזכור המקור הטכני.';

export type ReplyValidation = { ok: true } | { ok: false; error: string };

/** בדיקה לפני שמירת תשובה למורה: לא מזכירה את ספריית המקור */
export function validateReplyText(text: string): ReplyValidation {
  return mentionsSourceLibrary(text) ? { ok: false, error: REPLY_LIBRARY_ERROR } : { ok: true };
}

/* ------------------------------ תצוגה ------------------------------ */

const BEFORE_NAME = `[^.!?\\n]{0,60}?`;

/** תבניות שמסירות משפט-משנה שמזכיר את המקור. הסדר חשוב: מהספציפי לכללי */
const STRIP_PATTERNS: RegExp[] = [
  // "(מתוך ספריא)" / "(ספריא)" / "[ספריא]" – הסוגריים כולם
  new RegExp(`\\s*[\\(\\[][^()\\[\\]\\n]{0,60}?${NAME_WORD}[^()\\[\\]\\n]{0,40}?[\\)\\]]`, "gi"),
  // "…, כפי שהוא מופיע בספריא" / "כמו שמובא בספריא" / "כפי שנמצא באתר ספריא" – משפט-משנה שמסתיים בשם המקור
  new RegExp(`[ \\t]*[,;]?[ \\t]*(?:כפי|כמו)\\s+ש${BEFORE_NAME}(?:אתר\\s+|מאגר\\s+)?${NAME_WORD}`, "gi"),
  // "…, מתוך ספריא" / "לפי ספריא" / "על פי אתר ספריא" / "דרך ספריא"
  new RegExp(`[ \\t]*[,;]?[ \\t]*(?:מתוך|מן|לפי|על[- ]פי|דרך|באמצעות|בעזרת)\\s+(?:אתר\\s+|מאגר\\s+)?${NAME_WORD}`, "gi"),
  // "…, ממקור הנמצא בספריא" / "המופיע בספריא" / "המובא בספריא"
  new RegExp(`[ \\t]*[,;]?[ \\t]*(?:ה)?(?:מופיע|מופיעים|מובא|מובאים|נמצא|נמצאים|כתוב|כתובים)\\s+${NAME_WORD}`, "gi"),
];

/**
 * רשת ביטחון בתצוגה: מסירה מהתשובה משפט-משנה שמזכיר את המקור הטכני ("…, כפי שהוא מופיע בספריא."), ומשאירה את שאר
 * הטקסט כמות שהוא. שמרנית בכוונה: אם אחרי ההסרה השם עדיין מופיע (תבנית שלא הכרנו) – מחזירה את הטקסט המקורי בלי שינוי,
 * ולא מנחשת. החסימה האמיתית נעשית בעת השמירה (validateReplyText); זו רק הגנה על תשובות ישנות.
 */
export function sanitizeReplyForDisplay(text: string | null | undefined): string | null {
  if (text == null) return null;
  if (!mentionsSourceLibrary(text)) return text;
  let out = text;
  for (const re of STRIP_PATTERNS) out = out.replace(re, "");
  // ניקוי שאריות: רווחים כפולים, רווח לפני פיסוק, פסיק לפני נקודה, פסיק/נקודה-פסיק תלוי בסוף משפט/שורה
  out = out
    .replace(/[ \t]{2,}/g, " ")
    .replace(/ +([.,;:!?])/g, "$1")
    .replace(/[,;]+([.!?])/g, "$1")
    .replace(/[,;][ \t]*(?=\n|$)/g, ".")
    .replace(/[ \t]+\n/g, "\n")
    .trim();
  return mentionsSourceLibrary(out) || out.length === 0 ? text : out;
}
